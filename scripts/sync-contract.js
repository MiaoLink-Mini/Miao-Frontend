// The Gateway owns the wire contract. Generated JS works without npm/eval in wx.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const source = fs.readFileSync(path.resolve(__dirname, '../../WeAgent-Backend/contracts/protocol.schema.json'));
const schema = JSON.parse(source);
function compact(value) {
  if (Array.isArray(value)) return value.map(compact);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.entries(value).filter(([key, v]) => !(typeof v === 'string' && ['description', 'title', '$schema', '$id'].includes(key))).map(([key, v]) => [key, compact(v)]));
}
const output = '// Generated by scripts/sync-contract.js; do not edit.\n// source sha256: ' + crypto.createHash('sha256').update(source).digest('hex') + '\nmodule.exports = ' + JSON.stringify(compact(schema)) + ';\n';
const file = path.resolve(__dirname, '../miniprogram/services/protocol.generated.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== output) throw new Error('Gateway contract drift: run node scripts/sync-contract.js');
  console.log('Gateway contract is synchronized.');
} else fs.writeFileSync(file, output);
